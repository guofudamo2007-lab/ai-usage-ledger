"""Calibrate the offline comparisons with tiktoken 0.12.0 and fixed public editions."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web" / "reference-data.js"

# Tiny units for totals below the first editorial band.
EXAMPLES = {
    "reply": ("单字回复", "好"),
    "dot": ("句号", "。"),
    "question": ("问号", "？"),
}

# id, label, GITenberg repository, fixed revision, SHA-256 of the UTF-8 edition.
BOOKS = {
    "tao": (7337, "《道德经》繁体本", "---_7337", "8b925c01fc8ea15df485fb778f90315c4de8381b", "6abce56b84727e220f040ee49087e3d9b945d3ccde6eaa705e1051d26b03f490"),
    "crime": (2554, "《罪与罚》英译本", "Crime-and-Punishment_2554", "df32009e1d36b38bc4b010d6e19f8f529eeb4125", "32d94b3ad762826e9b13a0dec8e0a29985725084ac9dcbe55552a45e6abdac87"),
    "red": (24264, "《红楼梦》繁体本", "---_24264", "f86ffb9dd67165e3e17c29ab3ea3d29fd5d00d34", "20c795971786fd8eb2a00d35a1194b6dd3074b2afb4f4cd5a82ba3e10fe5dfaa"),
}
BOOK_BODY = re.compile(
    r"^\*\*\*\s*START OF (?:THIS|THE) PROJECT GUTENBERG[^\n]*\n"
    r"(.*?)^\*\*\*\s*END OF (?:THIS|THE) PROJECT GUTENBERG", re.M | re.I | re.S
)


def build(cache):
    os.environ.setdefault("TIKTOKEN_CACHE_DIR", str(cache / "encoding"))
    import tiktoken
    encoder = tiktoken.get_encoding("o200k_base")
    result = {key: len(encoder.encode_ordinary(text)) for key, (_, text) in EXAMPLES.items()}
    for key, (number, _, repo, revision, checksum) in BOOKS.items():
        path = cache / f"pg{number}.txt"
        file = f"{number}-0.txt"
        if not path.exists():
            address = f"https://raw.githubusercontent.com/GITenberg/{repo}/{revision}/{file}"
            with urlopen(address, timeout=45) as response:
                data = response.read()
        else:
            data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != checksum:
            raise ValueError(f"Unexpected edition of Gutenberg #{number}")
        if not path.exists():
            path.write_bytes(data)
        normalized = data.decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
        match = BOOK_BODY.search(normalized)
        if not match:
            raise ValueError(f"Missing text boundaries in Gutenberg #{number}")
        result[key] = len(encoder.encode_ordinary(match[1].strip()))
    return "// Generated by tools/build_references.py with o200k_base.\nexport const sampleTokens = " + json.dumps(result, indent=2) + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=ROOT / ".qa" / "reference-calibration")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    content = build(args.cache)
    if args.check:
        if content != OUTPUT.read_text(encoding="utf-8"):
            raise SystemExit("Reference counts differ from the calibrated catalogue.")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Calibrated {len(EXAMPLES)} text samples and {len(BOOKS)} public editions.")
